#!/usr/bin/env python3
"""Build the curated index (sections/19-index-body.tex) from data/index_terms.csv.

Each term maps to one or more LaTeX labels. Page numbers are resolved by LaTeX
(\\pageref, clickable); this script reads main.aux to (a) fail loudly on any
missing label and (b) drop duplicate targets that land on the same page.
Run after one pdflatex pass, then re-run pdflatex.
"""
import os, re, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
aux = open(os.path.join(ROOT, "main.aux"), encoding="latin-1").read()
pages = {}
for m in re.finditer(r"\\newlabel\{([^}]*)\}\{\{[^{}]*(?:\{[^{}]*\}[^{}]*)*\}\{([^}]*)\}", aux):
    pages[m.group(1)] = m.group(2)

entries, missing = [], []
for line in open(os.path.join(ROOT, "data", "index_terms.csv"), encoding="utf-8"):
    line = line.strip()
    if not line or line.startswith("#"):
        continue
    term, labels = line.split("|")
    seen, keep = set(), []
    for lab in labels.split(";"):
        lab = lab.strip()
        if lab not in pages:
            missing.append((term, lab))
            continue
        if pages[lab] in seen:
            continue
        seen.add(pages[lab])
        keep.append(lab)
    keep.sort(key=lambda l: int(pages[l]) if pages[l].isdigit() else 10**6)
    entries.append((term, keep))

if missing:
    print("MISSING LABELS:", missing)
    sys.exit(1)


def tex_escape(t):
    t = t.replace("&", r"\&").replace("_", r"\_")
    t = t.replace("S = k ln Omega", r"$S=k\ln\Omega$").replace("CO2", r"\ce{CO2}")
    t = t.replace("T-S", "$T$--$S$").replace("J-T", "J--T")
    t = re.sub(r"(?<=[A-Za-z])-(?=[A-Z])", "--", t)   # Churchill-Chu -> Churchill--Chu
    return t


def sortkey(t):
    return re.sub(r"[^a-z0-9 ]", "", t.lower())


entries.sort(key=lambda e: sortkey(e[0]))
out = []
letter = None
for term, labs in entries:
    first = sortkey(term)[:1].upper()
    if first != letter:
        letter = first
        out.append(r"\idxletter{%s}" % letter)
    refs = ", ".join(r"\pageref{%s}" % l for l in labs)
    out.append(r"\idxitem{%s}{%s}" % (tex_escape(term), refs))
with open(os.path.join(ROOT, "sections", "19-index-body.tex"), "w") as f:
    f.write("% generated by scripts/build_index.py -- do not edit\n")
    f.write("\n".join(out) + "\n")
print(f"{len(entries)} index entries written; {sum(len(e[1]) for e in entries)} page targets")
