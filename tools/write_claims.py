"""Render the public claims ledger from rebuilt artifacts, without promoting proxy labels."""

import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    results = json.loads((ROOT / "docs/results/results.json").read_text())
    inventory = json.loads((ROOT / "data/seed/crossings.geojson").read_text())[
        "features"
    ]
    tiers = Counter(f["properties"]["tier"] for f in inventory)
    up = results["methods"]["upstream_rule"]["avoid"]["pooled"]
    nearest = results["methods"]["nearest_gauge"]["avoid"]["pooled"]
    rows = [
        (
            "C-01",
            "Public inventory records (not deduplicated physical crossings)",
            str(len(inventory)),
            "data/seed/crossings.geojson · features.length",
        ),
        (
            "C-02",
            "Validated road thresholds",
            str(tiers["A"]),
            "data/overrides/overtop_stages.csv · reviewed rows",
        ),
        (
            "C-03",
            "Tier-B research candidates / Tier-C unmonitored records",
            f"{tiers['B']} / {tiers['C']}",
            "data/seed/crossings.geojson · tier",
        ),
        (
            "C-04",
            "Real archived storm windows",
            str(len(results["storms"])),
            "docs/results/results.json · storms",
        ),
        (
            "C-05",
            "Proxy reference cases / category onsets",
            f"{results['storms'][0]['n_crossings']} / {sum(s['n_onsets'] for s in results['storms'])}",
            "docs/results/results.json · storms[].n_crossings / n_onsets",
        ),
        (
            "C-06",
            "Assumed replay delivery delay",
            "60 minutes; not a measured historical distribution",
            "data/latency/gauge_latency.json · default_delay_min; n=0",
        ),
        (
            "C-07",
            "Candidate rule: proxy-gauge AVOID H/M/F; POD/FAR/CSI",
            f"{up['H']}/{up['M']}/{up['F']}; {up['pod']}/{up['far']}/{up['csi']}",
            "docs/results/results.json · methods.upstream_rule.avoid.pooled",
        ),
        (
            "C-08",
            "Median lead before a sourced downstream gauge-category threshold (not road flooding)",
            f"{up['median_lead_min']} min",
            "docs/results/results.json · methods.upstream_rule.avoid.pooled.median_lead_min",
        ),
        (
            "C-09",
            "True geodesic nearest-gauge rule: proxy AVOID H/M/F; POD/FAR/CSI",
            f"{nearest['H']}/{nearest['M']}/{nearest['F']}; {nearest['pod']}/{nearest['far']}/{nearest['csi']}",
            "docs/results/results.json · methods.nearest_gauge.avoid.pooled",
        ),
        (
            "C-10",
            "Deterministic closest-to-median reference example (no historical pre-registration claim)",
            str(results.get("hero")),
            "docs/results/results.json · hero; tools/select_hero.py",
        ),
        (
            "C-11",
            "Modeled delivery interruption",
            "2013-10-31 11:15Z–13:45Z; historical timing unverified",
            "data/storms/halloween-2013/meta.toml · outages",
        ),
        (
            "C-12",
            "Calm-control exposure",
            f"{results['assumptions']['calm_days']} days = 36 hours; full 30-day evaluation pending",
            "docs/results/results.json · assumptions.calm_days",
        ),
    ]
    lines = [
        "# FordCast Claims Ledger",
        "",
        "Generated by `uv run --project backend python tools/write_claims.py` after rebuilding artifacts.",
        "",
        "All scored labels are **reference-gauge category proxies**. No road-level flooding accuracy or positive gain over the repaired nearest-gauge comparator is claimed. Shared target gauges mean cases are not independent roads.",
        "",
        "| ID | Claim and scope | Current value | Evidence |",
        "|---|---|---|---|",
    ]
    lines += [
        f"| {code} | {claim} | {value} | {artifact} |"
        for code, claim, value, artifact in rows
    ]
    lines += [
        "",
        "Measured fields remain null when unavailable. Rejected calibration never gains a synthetic correlation or invented training-storm count. Geometry is explicitly schematic; candidate topology/channel distance and road-deck hydraulic transfer are unverified.",
        "",
        "Live ingestion, routing, push/background delivery, native-device behavior, fluent Spanish review, comprehension testing, competition eligibility, and student explain-back remain external acceptance gates. Watch preferences and alert previews are local only.",
        "",
        "Prior 89.3% detection, 70-minute road lead, 12 validated roads, nearest-gauge superiority and verified historical outage claims are withdrawn. The initial audit is retained as historical evidence, not current product claims.",
    ]
    (ROOT / "docs/CLAIMS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
