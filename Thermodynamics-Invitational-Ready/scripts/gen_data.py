NUMCELL = re.compile(r"^(\s*)(-?\d+(?:\.\d+)?)(\s*(?:\$\^\{?\\ddagger\}?\$)?\s*)$")


def numify(text):
    """Wrap purely numeric table cells in \\num{} (true minus signs, digit grouping)."""
    out = []
    for line in text.split("\n"):
        if "&" not in line or not line.rstrip().endswith("\\\\"):
            out.append(line); continue
        body = line.rstrip()[:-2]
        cells = []
        for c in body.split("&"):
            m = NUMCELL.match(c)
            cells.append(f"{m.group(1)}\\num{{{m.group(2)}}}{m.group(3)}" if m else c)
        out.append("&".join(cells) + "\\\\")
    return "\n".join(out)


def w(name, text, source):
    if name.endswith(".tex") and name not in ("constants.tex", "R_units.tex"):
        text = numify(text)
    with open(os.path.join(OUT, name), "w") as f:
        f.write("% generated by scripts/gen_data.py -- do not edit by hand\n")
        f.write(text)
    prov[name] = source


def sig(x, n=4):
    """Format to n significant figures, plain decimal where sensible."""
    if x == 0:
        return "0"
    d = n - int(math.floor(math.log10(abs(x)))) - 1
    d = max(d, 0)
    return f"{x:.{d}f}"


