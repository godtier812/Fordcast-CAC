// Builds extension/data.js from the FordCast mobile seed files.
// Usage: node tools/build_extension_data.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const seed = (f) => JSON.parse(readFileSync(join(root, 'mobile', 'assets', 'seed', f), 'utf8'));

const crossingsGeo = seed('crossings.json');
const linksRaw = seed('links.json');
const gaugesGeo = seed('gauges.json');

const round = (n) => Math.round(n * 1e6) / 1e6;

const crossings = (crossingsGeo.features ?? crossingsGeo).map((f) => ({
  id: f.properties.id,
  name: f.properties.name,
  creek: f.properties.creek ?? null,
  tier: f.properties.tier ?? null,
  lat: round(f.geometry.coordinates[1]),
  lon: round(f.geometry.coordinates[0]),
}));

const LINK_FIELDS = [
  'crossing_id',
  'gauge_id',
  'relation',
  'is_primary',
  'trigger_stage_ft',
  'watch_stage_ft',
  'rise_rate_ft_per_30m',
  'lag_p25_min',
  'lag_p75_min',
  'tau_lo_min',
  'tau_hi_min',
];
const links = linksRaw.map((l) => Object.fromEntries(LINK_FIELDS.map((k) => [k, l[k] ?? null])));

const gaugeIds = (gaugesGeo.features ?? gaugesGeo).map((g) => g.properties.id);

const data = { crossings, links, gaugeIds };
const out = join(root, 'extension', 'data.js');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  '// GENERATED by tools/build_extension_data.mjs from mobile/assets/seed — do not edit.\n' +
    `var FORDCAST_DATA = ${JSON.stringify(data)};\n` +
    "if (typeof module !== 'undefined') module.exports = FORDCAST_DATA;\n",
);
console.log(
  `Wrote ${out}: ${crossings.length} crossings, ${links.length} links, ${gaugeIds.length} gauges`,
);
