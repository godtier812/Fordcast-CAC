#!/usr/bin/env python3
"""Generate data/conversions.tex with every factor computed by pint (and the
exact defining values cross-checked against SciPy's CODATA-based constants).
Run: python3 scripts/gen_conversions.py
"""
import os, warnings
warnings.filterwarnings("ignore")
import pint, scipy.constants as sc

ureg = pint.UnitRegistry()
# pint's "Btu" is the rounded 1055.056 J; define the exact International Table Btu
ureg.define("BtuIT = 1055.05585262 * joule")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "data")

rows = [
    # label, from-unit, to-unit, latex unit text, digits, exact?
    ("1 thermochemical calorie", "calorie", "J", r"\si{J}", 4, True),
    ("1 International Table calorie", "international_calorie", "J", r"\si{J}", 5, True),
    ("1 Btu (International Table)", "BtuIT", "J", r"\si{J}", 8, True),
    ("1 kWh", "kWh", "MJ", r"\si{MJ}", 2, True),
    ("1 eV", "eV", "J", r"\si{J}", 10, True),
    ("1 L$\\cdot$atm", "L*atm", "J", r"\si{J}", 6, True),
    ("1 hp (mechanical)", "hp", "W", r"\si{W}", 5, False),
    ("1 Btu/h", "BtuIT/hour", "W", r"\si{W}", 5, False),
    ("1 ton of refrigeration (12\\,000 Btu/h)", "12000*BtuIT/hour", "kW", r"\si{kW}", 4, False),
    ("1 atm", "atm", "kPa", r"\si{kPa}", 6, True),
    ("1 atm", "atm", "torr", r"\si{Torr}", 3, True),
    ("1 atm", "atm", "psi", r"\si{psi}", 5, False),
    ("1 bar", "bar", "kPa", r"\si{kPa}", 3, True),
    ("1 Torr", "torr", "Pa", r"\si{Pa}", 4, False),
    ("1 psi", "psi", "kPa", r"\si{kPa}", 5, False),
    ("1 ft", "ft", "m", r"\si{m}", 4, True),
    ("1 in", "inch", "cm", r"\si{cm}", 2, True),
    ("1 ft$^3$", "ft**3", "L", r"\si{L}", 4, False),
    ("1 US gallon", "gallon", "L", r"\si{L}", 6, True),
    ("1 lbm", "lb", "kg", r"\si{kg}", 8, True),
    ("1 Btu/(lbm$\\cdot^\\circ$F)", "BtuIT/lb/delta_degF", "J/kg/K", r"\si{J/(kg.K)}", 1, True),
    ("1 Btu/(h$\\cdot$ft$\\cdot^\\circ$F)", "BtuIT/hour/ft/delta_degF", "W/m/K", r"\si{W/(m.K)}", 4, False),
    ("1 Btu/(h$\\cdot$ft$^2\\cdot^\\circ$F)", "BtuIT/hour/ft**2/delta_degF", "W/m**2/K", r"\si{W/(m^2.K)}", 4, False),
    ("1 ft$^2\\cdot^\\circ$F$\\cdot$h/Btu (US R-1)", "ft**2*delta_degF*hour/BtuIT", "m**2*K/W", r"\si{m^2.K/W}", 5, False),
]
lines = []
for lab, a, b, u, d, exact in rows:
    v = (1 * ureg(a)).to(b).magnitude
    if "eV" == a:
        assert abs(v - sc.eV) < 1e-30
        txt = r"\num{1.602176634e-19}"
    elif exact:
        txt = f"\\num{{{float(f'{v:.12g}'):.12g}}}"   # exact: show all significant digits
    else:
        txt = f"\\num{{{v:.{d}f}}}"
    lines.append(f"{lab} & {txt}\\,{u}{'$^\\ast$' if exact else ''}")
# cross-check a few against scipy
assert abs((1 * ureg("atm")).to("Pa").magnitude - sc.atm) < 1e-9
assert abs((1 * ureg("calorie")).to("J").magnitude - sc.calorie) < 1e-12
assert abs((1 * ureg("BtuIT")).to("J").magnitude - sc.Btu_IT) < 1e-9
assert abs((1 * ureg("lb")).to("kg").magnitude - sc.pound) < 1e-12
with open(os.path.join(OUT, "conversions.tex"), "w") as f:
    f.write(f"% generated by scripts/gen_conversions.py (pint {pint.__version__}) -- do not edit\n")
    half = (len(lines) + 1) // 2
    left, right = lines[:half], lines[half:] + [" & "] * (2 * half - len(lines))
    f.write("\n".join(f"{a} & {b}\\\\" for a, b in zip(left, right)) + "\n")
print("\n".join(lines))
